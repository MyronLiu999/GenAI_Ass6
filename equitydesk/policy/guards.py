"""Input guards and untrusted-content handling."""

from __future__ import annotations

import html
import re
import unicodedata

TICKER_RE = re.compile(r"^\^?[A-Z0-9][A-Z0-9.\-=]{0,11}$")   # AAPL, BRK-B, 7203.T, ^GSPC, EURUSD=X

# Instruction-like text in third-party content (news). A match flags the item in the prompt and the UI;
# the item stays visible as data, it is never followed.
INJECTION_PATTERNS = [re.compile(p, re.I) for p in (
    r"\b(ignore|disregard|forget)\b.{0,30}\b(instructions|prompt|rules|above)\b",
    r"\b(system|developer)\s*(prompt|message|instruction)",
    r"\byou are (now|an?)\b.{0,40}\b(assistant|ai|model|analyst)\b",
    r"<\s*/?\s*(system|assistant|user|instructions?|evidence|untrusted)\s*>",
    r"\b(rate|rating|recommend)\b.{0,25}\b(strong buy|strong sell)\b.{0,25}\b(regardless|no matter|must)\b",
    r"\bnew instructions?\b",
)]

DISCLAIMER = ("Research output generated by an automated multi-agent system from public market data. "
              "It is not investment advice, may contain errors, and places no orders. "
              "Verify every figure against primary sources before acting.")


class InputError(ValueError):
    """A request the desk refuses before any data is fetched or any model is called."""


def normalize_ticker(raw: str) -> str:
    t = (raw or "").strip().upper().replace(" ", "")
    if not TICKER_RE.match(t):
        raise InputError(f"'{raw}' is not a valid ticker symbol (letters, digits, '.', '-', '=', '^'; max 12).")
    return t


def sanitize_untrusted(text: str, max_len: int = 300) -> tuple[str, bool]:
    """Strip markup and control characters, collapse whitespace, cap length; flag injection patterns."""
    t = html.unescape(text or "")
    t = "".join(" " if unicodedata.category(ch)[0] == "C" else ch for ch in t)
    t = re.sub(r"\s+", " ", t).strip()
    flagged = any(p.search(t) for p in INJECTION_PATTERNS)  # checked before markup is stripped
    # Remove anything that could open or close our own prompt sections, or forge a citation.
    t = re.sub(r"<[^>]{0,200}>", " ", t).replace("[", "(").replace("]", ")")
    t = re.sub(r"\s+", " ", t).strip()
    if len(t) > max_len:
        t = t[: max_len - 1].rstrip() + "…"
    return t, flagged
